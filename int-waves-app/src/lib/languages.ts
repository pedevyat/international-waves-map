const LOWERCASE = new Map(Object.entries(LANGUAGES).map(([code, name]) => [code.toLowerCase(), name]))

/** Название языка по одному коду; неизвестный код возвращается как есть. */
export function languageName(code: string): string {
  const c = code.trim()
  return LANGUAGES[c] ?? LOWERCASE.get(c.toLowerCase()) ?? c
}

/** Поле «Lang.» может содержать несколько кодов через запятую («A,F» — арабский и французский). */
export function languageLabel(raw: string): string {
  return raw
    .split(/[,;+/]/)
    .map((c) => c.trim())
    .filter(Boolean)
    .map(languageName)
    .join(', ')
}