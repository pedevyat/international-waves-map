/** Название страны по коду ITU; неизвестный код возвращается как есть, пустой — undefined. */
export function countryName(code: string): string | undefined {
  return COUNTRIES[code.trim()]
}

export function countryLabel(raw: string): string {
  return raw
    .split(/[,;+/]/)
    .map((c) => c.trim())
    .filter(Boolean)
    .map(countryName)
    .join(', ')
}